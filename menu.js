// ---------- helpers ----------
export const categories = [...new Set(MENU.map(i => i.category))];

// Make Arabic spelling flexible: remove marks, unify أ/إ/آ, ى/ي, ة/ه
export const norm = s => String(s ?? '')
  .replace(/[\u064B-\u0652\u0640]/g, '').replace(/[أإآ]/g, 'ا').replace(/ى/g, 'ي').replace(/ة/g, 'ه')
  .replace(/\s+/g, ' ').trim().toLowerCase();

export const view = i => (i.sizes ? { name: i.name, sizes: i.sizes } : { name: i.name, price: i.price });

export function search(q) {
  const words = norm(q).split(' ').filter(Boolean);
  return MENU.filter(i => { const n = norm(i.name); return words.every(w => n.includes(w)); });
}

export function findOne(q) {
  const n = norm(q);
  const exact = MENU.filter(i => norm(i.name) === n);
  if (exact.length === 1) return { item: exact[0] };
  const found = exact.length ? exact : search(q);
  if (found.length === 1) return { item: found[0] };
  return { error: found.length ? 'Ambiguous: ask the client which one' : 'Not on the menu',
           options: found.slice(0, 6).map(i => i.name) };
}
